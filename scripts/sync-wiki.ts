/**
 * Sync wiki.warframe.com Lua modules into `data/raw/wiki/`.
 *
 * Fetches each module via `?action=raw` (no MediaWiki parsing, no API
 * authentication, no rate-limiting beyond the wiki's normal HTTP throttle).
 * Prepends a source-URL + license header comment to each file so the
 * provenance and CC-BY-SA attribution travels with the data.
 *
 * The router module `Module:Weapons/data` itself uses Scribunto's
 * `mw.loadData` + metatables and is NOT pure data — we mirror its eight
 * subpages instead, which are pure table literals safe to luaparse (see
 * WIKI_MODULES in build/read-wiki.ts for the full set).
 *
 * Network-only. The build never calls this; `read-wiki.ts` parses from disk.
 * Run via `bun run scripts/sync-wiki.ts` or as part of `bun run data:sync`.
 * Pass module names (`bun run scripts/sync-wiki.ts Ability/data/stats`) to
 * mirror only those, keeping every other module's file and pin as it is.
 */

import { createHash } from "node:crypto"
import { mkdir, writeFile } from "node:fs/promises"
import { resolve } from "node:path"

import { fetchText } from "./build/http"
import { RAW_WIKI_DIR as OUT_DIR } from "./build/paths"
import { readPins, writePinsSection, type WikiPin } from "./build/pins"
import { WIKI_MODULES as MODULES, wikiModuleFile } from "./build/read-wiki"

async function main() {
  const only = process.argv.slice(2)
  const unknown = only.filter(
    (m) => !(MODULES as readonly string[]).includes(m),
  )
  if (unknown.length) throw new Error(`Not in MODULES: ${unknown.join(", ")}`)
  const selected = only.length ? only : MODULES
  console.log(`Mirroring ${selected.length} wiki modules to ${OUT_DIR}…`)
  await mkdir(OUT_DIR, { recursive: true })

  // A partial run keeps the pins of the modules it didn't re-fetch, minus
  // modules since dropped from MODULES.
  const existing = only.length ? (await readPins()).wiki?.modules : undefined
  const pins: WikiPin[] = (existing ?? []).filter(
    (p) =>
      !only.includes(p.module) &&
      (MODULES as readonly string[]).includes(p.module),
  )
  for (const m of selected) {
    const url = `https://wiki.warframe.com/index.php?title=Module:${m}&action=raw`
    process.stdout.write(`  Module:${m}… `)
    const body = await fetchText(url)
    const header =
      `-- Source: ${url}\n` +
      `-- Mirror license: CC-BY-SA 4.0 (https://creativecommons.org/licenses/by-sa/4.0/)\n` +
      `-- Mirrored: ${new Date().toISOString()}\n` +
      `-- DO NOT EDIT — regenerated by scripts/sync-wiki.ts\n` +
      `\n`
    const content = header + body
    const file = wikiModuleFile(m)
    await writeFile(resolve(OUT_DIR, file), content, "utf8")
    pins.push({
      module: m,
      file,
      sha256: createHash("sha256").update(body).digest("hex"),
      bytes: body.length,
      fetchedAt: new Date().toISOString(),
    })
    process.stdout.write(`${(body.length / 1024).toFixed(1)} KB\n`)
  }

  await writePinsSection("wiki", {
    fetchedAt: new Date().toISOString(),
    modules: pins,
  })

  console.log(`\n✓ ${selected.length} modules → data/raw/wiki/`)
  console.log(`✓ data/PINS.json updated with wiki section`)
}

main().catch((err) => {
  console.error(err)
  process.exit(1)
})
